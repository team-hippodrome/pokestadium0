#!/usr/bin/env python3
"""Write src/subtitles_en.h from text/subtitles.json, the English lines of Zero's spoken sound effects.

text/subtitles.json has one entry per effect id of each effect table (announcer = JIKKYOU.WBK,
battle = BTLSFX.WBK, system = SYSSFX.WBK, whose effects may play another bank's samples): kind
(voice, sfx, unknown, none), jp, en, review, note. An effect gets a
subtitle when its kind is voice and en is set; everything else is NULL. The Zero studio in
pokestadium-research/stadium-assets edits the JSON with the audio next to it; `make en` runs this.

usage: subtitles.py [generate] [--json text/subtitles.json] [--out src/subtitles_en.h]
       subtitles.py selftest
"""

import argparse
import json
from pathlib import Path

BANKS = (('announcer', 'sSubtitleAnnouncer', 'JIKKYOU.WBK, the announcer'),
         ('battle', 'sSubtitleBattle', 'BTLSFX.WBK, the battle sound effects'),
         ('system', 'sSubtitleSystem', 'SYSSFX.WBK\'s effect table, the system sounds'))
WIDTH = 34  # characters per line in the subtitle box (src/stage_loader.c)


def c_string(text):
    # `@` draws é: Stadium 1's ASCII map, which the English font uses, points it there.
    return '"%s"' % text.replace('é', '@').encode('ascii', 'replace').decode().replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def header(data):
    out = ['/*',
           ' * Generated by tools/subtitles.py from text/subtitles.json; edit that file (or the Zero studio)',
           ' * and run `make en`. One line per sound effect id; NULL = no subtitle.',
           ' */']
    for bank, name, what in BANKS:
        entries = data[bank]
        count = max(int(key, 16) for key in entries) + 1
        out.append('')
        out.append('/* %s */' % what)
        out.append('static const char* const %s[%d] = {' % (name, count))
        for index in range(count):
            entry = entries.get('0x%02X' % index, {})
            text = entry.get('en', '') if entry.get('kind') == 'voice' else ''
            for line in text.split('\n'):
                if len(line) > WIDTH:
                    raise SystemExit('%s 0x%02X: "%s" is wider than %d characters' % (bank, index, line, WIDTH))
            comment = ' '.join(entry.get('jp', '').split()).replace('*/', '* /')
            flag = ' REVIEW' if entry.get('review') else ''
            out.append('    /* 0x%02X%s%s */ %s,' % (index, (' ' + comment) if comment else '', flag,
                                                   c_string(text) if text else 'NULL'))
        out.append('};')
    return '\n'.join(out) + '\n'


def selftest():
    data = {'announcer': {'0x00': {'kind': 'none'}, '0x02': {'kind': 'voice', 'jp': 'さあ', 'en': 'Go!\nNow', 'review': True}},
            'battle': {'0x00': {'kind': 'sfx', 'en': 'not shown'}, '0x01': {'kind': 'unknown', 'en': 'not shown'}},
            'system': {'0x00': {'kind': 'none'}}}
    text = header(data)
    assert 'sSubtitleAnnouncer[3]' in text and '/* 0x02 さあ REVIEW */ "Go!\\nNow",' in text, text
    assert 'not shown' not in text and 'sSubtitleBattle[2]' in text, text
    try:
        header({'announcer': {'0x00': {'kind': 'voice', 'en': 'x' * (WIDTH + 1)}}, 'battle': {'0x00': {}},
                'system': {'0x00': {}}})
    except SystemExit:
        pass
    else:
        raise AssertionError('an over-wide line was accepted')
    print('selftest ok')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('command', nargs='?', default='generate', choices=['generate', 'selftest'])
    ap.add_argument('--json', default='text/subtitles.json')
    ap.add_argument('--out', default='src/subtitles_en.h')
    args = ap.parse_args()
    if args.command == 'selftest':
        return selftest()
    text = header(json.loads(Path(args.json).read_text(encoding='utf-8')))
    out = Path(args.out)
    if not out.exists() or out.read_text(encoding='utf-8') != text:
        out.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', out)


if __name__ == '__main__':
    main()
