#!/usr/bin/env python3
"""Regenerate COVERAGE.md from the full-ROM build receipt.

The denominator is the first-pass assembly-owner inventory, not a recovered
original function count, minus the handwritten assembly listed in
docs/handwritten-asm.csv, which is reported on its own line. C owners are the build=c rows of
docs/function-matches.csv in the source files the receipt built.
"""
import csv
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def production():
    receipt = json.loads((ROOT / 'docs/production-build-receipt.json').read_text())
    if (receipt.get('status') != 'PASS' or not receipt['full_rom_identical']
            or receipt['input_sha256'] != receipt['output_sha256']):
        raise ValueError('coverage requires a current full-ROM PASS receipt')
    for path, key in (('config/jp/matching.json', 'matching_registry_sha256'),
                      ('config/jp/sources.json', 'source_registry_sha256'),
                      ('config/jp/sections.json', 'section_registry_sha256')):
        if receipt[key] != digest(ROOT / path):
            raise ValueError('receipt is stale for ' + path + '; rebuild and refresh receipt')
    sys.path.insert(0, str(ROOT / 'tools'))
    from production import headers_digest
    if receipt['headers_sha256'] != headers_digest():
        raise ValueError('receipt is stale for headers; rebuild and refresh receipt')
    for path, expected in {**receipt['c_sources_sha256'], **receipt['build_tools_sha256'],
                           **receipt.get('original_assembly_sources_sha256', {})}.items():
        if digest(ROOT / path) != expected:
            raise ValueError('receipt is stale for ' + path + '; rebuild and refresh receipt')
    return receipt


def main() -> int:
    inventory = json.loads((ROOT / "docs/pragma-inventory.json").read_text())
    sizes = {row["name"]: row["size"] for row in inventory["owners"]}
    with (ROOT / "docs/function-matches.csv").open() as handle:
        rows = list(csv.DictReader(handle))
    receipt = production()
    built = set(receipt['source_files'])
    total = len(sizes)
    total_bytes = sum(sizes.values())
    c_rows = [row for row in rows if row["build"] == "c" and row["source"] in built]
    if len(c_rows) != receipt['c_owners']:
        raise ValueError('receipt C count differs from docs/function-matches.csv')
    with (ROOT / "docs/handwritten-asm.csv").open() as handle:
        handwritten = {row["owner"] for row in csv.DictReader(handle)}
    unknown = handwritten - set(sizes)
    if unknown:
        raise ValueError('docs/handwritten-asm.csv names unknown owners: ' + ', '.join(sorted(unknown)))
    hw_bytes = sum(sizes[name] for name in handwritten)
    hw_c = [row for row in c_rows if row["owner"] in handwritten]
    c_rows = [row for row in c_rows if row["owner"] not in handwritten]
    total -= len(handwritten)
    total_bytes -= hw_bytes
    c_bytes = sum(sizes[row["owner"]] for row in c_rows)
    sdk_rows = [row for row in rows if row['status'] == 'ultralib-asm'
                and row['source'] in built]
    if len(sdk_rows) != receipt.get('sdk_asm_owners', 0):
        raise ValueError('receipt SDK assembly count differs from docs/function-matches.csv')
    ordinary_sdk = [row for row in sdk_rows if row['owner'] not in handwritten]
    hw_sdk = [row for row in sdk_rows if row['owner'] in handwritten]
    all_c_count = len(c_rows) + len(hw_c)
    all_c_bytes = c_bytes + sum(sizes[row['owner']] for row in hw_c)
    sdk_bytes = sum(sizes[row['owner']] for row in sdk_rows)
    status = Counter(row["status"] for row in c_rows)
    held = [row for row in rows if row["status"] in ("s1", "m2c", "hand") and row["build"] != "c"]
    libultra = [row for row in rows if row["origin"].startswith("libultra:")
                and row["build"] != "c" and row['status'] != 'ultralib-asm']
    lib_bytes = sum(sizes[row["owner"]] for row in libultra)
    text = f"""<!-- Generated by ci/update_coverage.py. Do not edit by hand. -->

# pokestadium0 decompilation coverage

<!-- AUTO_COVERAGE:START -->
- Code owners (first-pass function inventory, excluding handwritten assembly): **{total:,}** covering **{total_bytes:,}** text bytes
- Built from C in the full-ROM build: **{len(c_rows):,} / {total:,} ({100 * len(c_rows) / total:.1f}%)**, **{c_bytes:,}** bytes ({100 * c_bytes / total_bytes:.1f}%)
  - ported from the Stadium 1 decomp: **{status['s1']:,}**
  - m2c output: **{status['m2c']:,}**
  - matched by hand: **{status['hand']:,}**
  - unmodified ultralib 2.0I sources (`lib/ultralib`): **{status['ultralib']:,}**
- Built from original SDK assembly: **{len(sdk_rows):,}**, **{sdk_bytes:,}** bytes
- Covered by C or original SDK source across the complete inventory (including handwritten owners): **{all_c_count + len(sdk_rows):,} / {len(sizes):,} ({100 * (all_c_count + len(sdk_rows)) / len(sizes):.1f}%)**, **{all_c_bytes + sdk_bytes:,}** bytes ({100 * (all_c_bytes + sdk_bytes) / sum(sizes.values()):.1f}%)
- Matching C held behind `NON_MATCHING` until its file's data is placed: **{len(held):,}**
- Identified libultra functions still using extracted assembly (including handwritten owners): **{len(libultra):,}**, **{lib_bytes:,}** bytes
- Remaining ordinary assembly owners: **{total - len(c_rows):,}** ({total - len(c_rows) - len(ordinary_sdk):,} still extracted)
- Handwritten assembly, counted separately from the ordinary totals above ([list](docs/handwritten-asm.csv)): **{len(handwritten):,}** owners, **{hw_bytes:,}** bytes ({len(hw_c):,} built from C; {len(hw_sdk):,} from original SDK assembly)
- Remaining extracted assembly across the complete inventory: **{len(sizes) - len(c_rows) - len(hw_c) - len(sdk_rows):,}**
- Complete ROM comparison: **PASS**, SHA-256 `{receipt['output_sha256']}`
<!-- AUTO_COVERAGE:END -->

`make rom` compiles every file in [config/jp/sources.json](config/jp/sources.json)
and fails unless each linked image and the complete ROM are identical to the
retail ROM; [the receipt](docs/production-build-receipt.json) records the last
passing build. Counts use the conservative first-pass assembly-owner inventory,
not confirmed original functions or translation units. Data, `.rodata`,
microcode, opaque ranges and resource-only images are excluded from the
owner-byte denominator and still come from the extracted ROM.

See [the production build](docs/production-build.md) and
[docs/matching.md](docs/matching.md). Regenerate with `make coverage` after
refreshing the receipt.
"""
    out = ROOT / "COVERAGE.md"
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
